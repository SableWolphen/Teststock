import fs from 'node:fs/promises';
const s=JSON.parse(await fs.readFile('docs/signal.json','utf8'));
const p=s.claudeExecutionPolicy||{};
const fail=[];
if(Number(s.schemaVersion)<36)fail.push('schema <36');
if(s.autopilot?.executionAgent!=='CLAUDE')fail.push('Claude execution agent');
if(s.autopilot?.stockBuysRequireCurrentBatchApproval!==false)fail.push('stock batch approval still enabled');
if(s.autopilot?.stockBuysRequireUserApproval!==false)fail.push('stock user approval still enabled');
if(s.autopilot?.cryptoBuysRequireUserApproval!==false)fail.push('crypto approval should be false');
if(s.autopilot?.automaticQualifiedStockBuys!==true)fail.push('automatic stock buys');
if(s.autopilot?.automaticQualifiedCryptoBuys!==true)fail.push('automatic crypto buys');
if(s.autopilot?.automaticRiskReducingExits!==true)fail.push('automatic exits');
if(p.enabled!==true)fail.push('policy enabled');
if(p.role!=='SOLE_EXECUTION_AGENT')fail.push('sole execution role');
if(p.schedule?.cron!=='*/5 * * * *')fail.push('cron');
if(p.triggerBoardFirst!==true)fail.push('trigger-board first');
if(p.sourceOfTruth!=='LATEST_RAW_MAIN')fail.push('raw-main source');
if(p.generationMatchRequired!==true)fail.push('generation match');
if(p.exits?.explicitApprovalRequired!==false)fail.push('exit approval');
if(p.exits?.automaticWhenDetectedAndBrokerPermits!==true)fail.push('automatic exit permission');
if(p.stockBuys?.executionOwner!=='CLAUDE')fail.push('stock execution owner');
if(p.stockBuys?.explicitApprovalRequired!==false)fail.push('stock approval required');
if(p.stockBuys?.automaticWhenFullyQualifiedAndBrokerPermits!==true)fail.push('automatic stock buy disabled');
if(p.stockBuys?.requireRobinhoodTradingMcp!==true)fail.push('stock Robinhood Trading MCP');
if(p.crypto?.executionOwner!=='CLAUDE')fail.push('crypto execution owner');
if(p.crypto?.explicitApprovalRequired!==false)fail.push('crypto approval');
if(p.crypto?.automaticWhenFullyQualifiedAndBrokerPermits!==true)fail.push('crypto automatic execution');
if(p.crypto?.directGitHubOrderSubmissionAllowed!==false)fail.push('direct GitHub crypto execution');
if(p.crypto?.requireRobinhoodTradingMcp!==true)fail.push('crypto Robinhood Trading MCP');
if(p.brokerExecutionContract?.executor!=='CLAUDE_ONLY')fail.push('broker execution owner');
if(p.brokerExecutionContract?.transport!=='ROBINHOOD_TRADING_MCP')fail.push('broker transport');
if(s.generatorIntegrity?.traceableFeatures?.automaticStockExecution!==true)fail.push('automatic stock integrity feature');
if(s.generatorIntegrity?.traceableFeatures?.automaticCryptoExecution!==true)fail.push('automatic crypto integrity feature');
if(s.generatorIntegrity?.traceableFeatures?.claudeSoleExecutionAgent!==true)fail.push('sole-executor integrity feature');
if(fail.length)throw new Error(`Claude automatic execution policy validation failed: ${[...new Set(fail)].join(', ')}`);
console.log('Claude automatic execution policy validation passed: stocks + crypto + exits automatic through Robinhood Trading MCP.');
