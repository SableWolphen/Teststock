import fs from 'node:fs/promises';
const s=JSON.parse(await fs.readFile('docs/signal.json','utf8'));
const p=s.claudeExecutionPolicy||{};
const fail=[];
if(Number(s.schemaVersion)<35)fail.push('schema <35');
if(s.autopilot?.executionAgent!=='CLAUDE')fail.push('Claude execution agent');
if(s.autopilot?.stockBuysRequireCurrentBatchApproval!==true)fail.push('stock batch approval gate');
if(s.autopilot?.cryptoBuysRequireUserApproval!==false)fail.push('crypto approval should be false');
if(s.autopilot?.automaticRiskReducingExits!==true)fail.push('automatic exits');
if(p.enabled!==true)fail.push('policy enabled');
if(p.role!=='SOLE_EXECUTION_AGENT')fail.push('sole execution role');
if(p.schedule?.cron!=='0 13-21 * * 1-5')fail.push('cron');
if(p.triggerBoardFirst!==true)fail.push('trigger-board first');
if(p.sourceOfTruth!=='LATEST_RAW_MAIN')fail.push('raw-main source');
if(p.generationMatchRequired!==true)fail.push('generation match');
if(p.exits?.explicitApprovalRequired!==false)fail.push('exit approval');
if(p.exits?.automaticWhenDetectedAndBrokerPermits!==true)fail.push('automatic exit permission');
if(p.stockBuys?.explicitApprovalRequired!==true)fail.push('stock approval required');
if(p.stockBuys?.automaticWhenFullyQualifiedAndBrokerPermits!==false)fail.push('automatic stock buy');
if(p.stockBuys?.batchApprovalAllowed!==true)fail.push('batch approval disabled');
if(p.stockBuys?.approvalScope!=='CURRENT_EXACT_DISPATCH_ONLY')fail.push('approval scope');
if(!Array.isArray(p.stockBuys?.appliesTo)||p.stockBuys.appliesTo.some(x=>!['STOCK_A','STOCK_B'].includes(x)))fail.push('stock-only buy scope');
if(p.crypto?.executionOwner!=='CLAUDE')fail.push('crypto execution owner');
if(p.crypto?.explicitApprovalRequired!==false)fail.push('crypto approval');
if(p.crypto?.automaticWhenFullyQualifiedAndBrokerPermits!==true)fail.push('crypto automatic execution');
if(p.crypto?.directGitHubOrderSubmissionAllowed!==false)fail.push('direct GitHub crypto execution');
if(p.brokerExecutionContract?.executor!=='CLAUDE_ONLY')fail.push('broker execution owner');
if(s.generatorIntegrity?.traceableFeatures?.claudeSoleExecutionAgent!==true)fail.push('integrity feature');
if(fail.length)throw new Error(`Claude approval/execution policy validation failed: ${[...new Set(fail)].join(', ')}`);
console.log('Claude approval/execution policy validation passed: exact current-batch stock approval + automatic qualified crypto through Claude.');
