import fs from 'node:fs/promises';
const s=JSON.parse(await fs.readFile('docs/signal.json','utf8'));
const p=s.claudeExecutionPolicy||{};
const fail=[];
if(Number(s.schemaVersion)<32)fail.push('schema <32');
if(s.autopilot?.requiresPerOrderApproval!==true)fail.push('buy approval gate');
if(s.autopilot?.automaticRiskReducingExits!==true)fail.push('automatic exits');
if(p.enabled!==true)fail.push('policy enabled');
if(p.schedule?.cron!=='0 13-21 * * 1-5')fail.push('cron');
if(p.triggerBoardFirst!==true)fail.push('trigger-board first');
if(p.sourceOfTruth!=='LATEST_RAW_MAIN')fail.push('raw-main source');
if(p.generationMatchRequired!==true)fail.push('generation match');
if(p.exits?.explicitApprovalRequired!==false)fail.push('exit approval');
if(p.exits?.automaticWhenDetectedAndBrokerPermits!==true)fail.push('automatic exit permission');
if(p.buys?.explicitApprovalRequired!==true)fail.push('buy approval required');
if(p.buys?.automaticWhenFullyQualifiedAndBrokerPermits!==false)fail.push('automatic stock buy');
if(!Array.isArray(p.buys?.appliesTo)||p.buys.appliesTo.some(x=>!['STOCK_A','STOCK_B'].includes(x)))fail.push('stock-only buy scope');
if(s.generatorIntegrity?.traceableFeatures?.perOrderStockApproval!==true)fail.push('integrity feature');
if(fail.length)throw new Error(`Claude hourly approval policy validation failed: ${[...new Set(fail)].join(', ')}`);
console.log('Claude hourly approval policy validation passed.');
