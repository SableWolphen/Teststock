import fs from 'node:fs/promises';
const s=JSON.parse(await fs.readFile('docs/signal.json','utf8'));
const fail=[];
if(Number(s.schemaVersion)<35)fail.push('schema <35');
if(s.autopilot?.enabled!==true)fail.push('autopilot disabled');
if(s.autopilot?.executionAgent!=='CLAUDE')fail.push('Claude not canonical executor');
if(s.autopilot?.stockBuysRequireCurrentBatchApproval!==true)fail.push('stock batch approval disabled');
if(s.autopilot?.cryptoBuysRequireUserApproval!==false)fail.push('crypto incorrectly requires user approval');
if(s.autopilot?.automaticQualifiedCryptoBuys!==true)fail.push('automatic qualified crypto buys disabled');
if(s.autopilot?.automaticRiskReducingExits!==true)fail.push('automatic exits disabled');
if(s.autopilot?.directGitHubBrokerExecution!==false)fail.push('direct GitHub execution enabled');
const p=s.claudeExecutionPolicy;
if(p?.enabled!==true)fail.push('Claude execution policy disabled');
if(p?.role!=='SOLE_EXECUTION_AGENT')fail.push('Claude role');
if(p?.schedule?.cron!=='0 13-21 * * 1-5')fail.push('Claude cron metadata');
if(p?.triggerBoardFirst!==true)fail.push('trigger board first');
if(p?.executionWatchlistPath!=='docs/data/execution-watchlist.json')fail.push('execution watchlist path');
if(p?.sourceOfTruth!=='LATEST_RAW_MAIN')fail.push('raw-main source');
if(p?.generationMatchRequired!==true)fail.push('generation match');
if(p?.stockBuys?.explicitApprovalRequired!==true)fail.push('stock approval required');
if(p?.stockBuys?.automaticWhenFullyQualifiedAndBrokerPermits!==false)fail.push('automatic stock buy rule');
if(p?.stockBuys?.batchApprovalAllowed!==true)fail.push('stock batch approval');
if(p?.stockBuys?.approvalScope!=='CURRENT_EXACT_DISPATCH_ONLY')fail.push('stock approval scope');
if(JSON.stringify(p?.stockBuys?.appliesTo)!==JSON.stringify(['STOCK_A','STOCK_B']))fail.push('stock buy scope');
if(JSON.stringify(p?.stockBuys?.stockPriority)!==JSON.stringify(['A','B']))fail.push('A/B priority');
if(p?.stockBuys?.bTierUsesReducedEncodedSize!==true)fail.push('B reduced size');
if(p?.stockBuys?.perFutureOrderStandingApprovalAllowed!==false)fail.push('future standing approval allowed');
if(p?.crypto?.executionOwner!=='CLAUDE')fail.push('crypto execution owner');
if(p?.crypto?.explicitApprovalRequired!==false)fail.push('crypto approval rule');
if(p?.crypto?.automaticWhenFullyQualifiedAndBrokerPermits!==true)fail.push('crypto automatic execution rule');
if(p?.crypto?.directGitHubOrderSubmissionAllowed!==false)fail.push('GitHub crypto order submission allowed');
if(p?.crypto?.requireOfficialRobinhoodCryptoApi!==true)fail.push('official Robinhood crypto API not required');
if(p?.crypto?.manualHoldingsIsolationRequired!==true)fail.push('manual crypto isolation');
if(p?.brokerExecutionContract?.executor!=='CLAUDE_ONLY')fail.push('broker executor contract');
if(p?.brokerExecutionContract?.duplicateProtectionRequired!==true)fail.push('duplicate protection');
if(p?.brokerExecutionContract?.reconcileByClientOrderId!==true)fail.push('client order reconciliation');
if(p?.brokerExecutionContract?.neverAssumeFill!==true)fail.push('fill verification');
if(p?.exits?.explicitApprovalRequired!==false||p?.exits?.automaticWhenDetectedAndBrokerPermits!==true)fail.push('automatic exit rule');
if(!Array.isArray(p?.hardGuardsRemainMandatory)||p.hardGuardsRemainMandatory.length<10)fail.push('hard guards');
if(p?.accountGuardrailSource?.source!=='CURRENT_RAW_MAIN_SIGNAL_ONLY')fail.push('guardrail source');
if(p?.accountGuardrailSource?.legacyNinetyDollarPauseThresholdAllowed!==false)fail.push('legacy $90 threshold not blocked');
if(p?.accountGuardrailSource?.idleAccountLookupAllowed!==false)fail.push('idle account lookup allowed');
if(p?.protectionReconciliation?.enabled!==true)fail.push('protection reconciliation disabled');
if(p?.protectionReconciliation?.projectsOrDriveRequiredForWatchlistRead!==false)fail.push('Projects/Drive dependency');
if(p?.protectionReconciliation?.idleRepairExceptionAllowed!==true)fail.push('idle repair exception disabled');
if(p?.protectionReconciliation?.neverInventLevels!==true)fail.push('repair may invent levels');
if(p?.idle?.robinhoodCallsOnNormalIdle!==false)fail.push('normal idle Robinhood calls allowed');
if(JSON.stringify(p?.idle?.normalReads)!==JSON.stringify(['docs/data/trigger-board.json','docs/data/execution-watchlist.json']))fail.push('idle read set');
if(s.generatorIntegrity?.traceableFeatures?.claudeUnattendedExecutionPolicy!==true)fail.push('integrity marker');
if(s.generatorIntegrity?.traceableFeatures?.claudeSoleExecutionAgent!==true)fail.push('sole-executor integrity marker');
if(s.generatorIntegrity?.traceableFeatures?.idleProtectionReconciliation!==true)fail.push('repair integrity marker');
if(fail.length)throw new Error(`unattended execution validation failed: ${[...new Set(fail)].join(', ')}`);
console.log('Claude sole-execution validation passed: exact-batch-approved stock buys, automatic qualified crypto, automatic verified exits, no direct GitHub broker execution.');
