import fs from 'node:fs/promises';
const s=JSON.parse(await fs.readFile('docs/signal.json','utf8'));
const fail=[];
if(Number(s.schemaVersion)<36)fail.push('schema <36');
if(s.autopilot?.enabled!==true)fail.push('autopilot disabled');
if(s.autopilot?.executionAgent!=='CLAUDE')fail.push('Claude not canonical executor');
if(s.autopilot?.stockBuysRequireCurrentBatchApproval!==false)fail.push('stock batch approval still required');
if(s.autopilot?.stockBuysRequireUserApproval!==false)fail.push('stock approval still required');
if(s.autopilot?.cryptoBuysRequireUserApproval!==false)fail.push('crypto approval still required');
if(s.autopilot?.automaticQualifiedStockBuys!==true)fail.push('automatic stock buys disabled');
if(s.autopilot?.automaticQualifiedCryptoBuys!==true)fail.push('automatic crypto buys disabled');
if(s.autopilot?.automaticRiskReducingExits!==true)fail.push('automatic exits disabled');
if(s.autopilot?.directGitHubBrokerExecution!==false)fail.push('direct GitHub execution enabled');
const p=s.claudeExecutionPolicy;
if(p?.enabled!==true)fail.push('policy disabled');
if(p?.role!=='SOLE_EXECUTION_AGENT')fail.push('Claude role');
if(p?.schedule?.cron!=='*/5 * * * *')fail.push('Claude schedule');
if(p?.triggerBoardFirst!==true)fail.push('trigger board first');
if(p?.executionWatchlistPath!=='docs/data/execution-watchlist.json')fail.push('watchlist path');
if(p?.sourceOfTruth!=='LATEST_RAW_MAIN')fail.push('raw-main source');
if(p?.generationMatchRequired!==true)fail.push('generation match');
if(p?.stockBuys?.executionOwner!=='CLAUDE')fail.push('stock execution owner');
if(p?.stockBuys?.explicitApprovalRequired!==false)fail.push('stock approval rule');
if(p?.stockBuys?.automaticWhenFullyQualifiedAndBrokerPermits!==true)fail.push('automatic stock rule');
if(p?.stockBuys?.requireRobinhoodTradingMcp!==true)fail.push('stock MCP requirement');
if(p?.stockBuys?.requireLiveBrokerRecheck!==true)fail.push('stock live broker recheck');
if(!Array.isArray(p?.stockBuys?.appliesTo)||!['STOCK_A','STOCK_B','STOCK_SEED','STOCK_DAY_TRADE_SEED'].every(x=>p.stockBuys.appliesTo.includes(x)))fail.push('stock buy scope');
if(p?.crypto?.executionOwner!=='CLAUDE')fail.push('crypto execution owner');
if(p?.crypto?.explicitApprovalRequired!==false)fail.push('crypto approval rule');
if(p?.crypto?.automaticWhenFullyQualifiedAndBrokerPermits!==true)fail.push('crypto automatic rule');
if(p?.crypto?.directGitHubOrderSubmissionAllowed!==false)fail.push('GitHub crypto submission allowed');
if(p?.crypto?.requireRobinhoodTradingMcp!==true)fail.push('crypto MCP requirement');
if(p?.crypto?.requireLiveBrokerRecheck!==true)fail.push('crypto live broker recheck');
if(p?.crypto?.manualHoldingsIsolationRequired!==true)fail.push('manual crypto isolation');
if(p?.brokerExecutionContract?.executor!=='CLAUDE_ONLY')fail.push('broker executor');
if(p?.brokerExecutionContract?.transport!=='ROBINHOOD_TRADING_MCP')fail.push('broker transport');
if(p?.brokerExecutionContract?.duplicateProtectionRequired!==true)fail.push('duplicate protection');
if(p?.brokerExecutionContract?.reconcileByClientOrderId!==true)fail.push('client order reconciliation');
if(p?.brokerExecutionContract?.neverAssumeFill!==true)fail.push('fill verification');
if(p?.exits?.explicitApprovalRequired!==false||p?.exits?.automaticWhenDetectedAndBrokerPermits!==true)fail.push('automatic exit rule');
if(!Array.isArray(p?.exits?.scope)||!p.exits.scope.includes('STOCK_DAY_TRADE_FORCED_EXIT'))fail.push('day-trade exit scope');
if(!Array.isArray(p?.hardGuardsRemainMandatory)||p.hardGuardsRemainMandatory.length<10)fail.push('hard guards');
if(p?.accountGuardrailSource?.source!=='CURRENT_RAW_MAIN_SIGNAL_ONLY')fail.push('guardrail source');
if(p?.accountGuardrailSource?.legacyNinetyDollarPauseThresholdAllowed!==false)fail.push('legacy threshold');
if(p?.accountGuardrailSource?.idleAccountLookupAllowed!==false)fail.push('idle account lookup');
if(p?.protectionReconciliation?.enabled!==true)fail.push('protection reconciliation');
if(p?.protectionReconciliation?.neverInventLevels!==true)fail.push('invented protection levels');
if(p?.idle?.robinhoodCallsOnNormalIdle!==false)fail.push('idle Robinhood calls');
if(s.generatorIntegrity?.traceableFeatures?.claudeSoleExecutionAgent!==true)fail.push('sole-executor marker');
if(s.generatorIntegrity?.traceableFeatures?.automaticStockExecution!==true)fail.push('automatic-stock marker');
if(s.generatorIntegrity?.traceableFeatures?.automaticCryptoExecution!==true)fail.push('automatic-crypto marker');
if(s.generatorIntegrity?.traceableFeatures?.robinhoodTradingMcpExecution!==true)fail.push('MCP marker');
if(fail.length)throw new Error(`unattended execution validation failed: ${[...new Set(fail)].join(', ')}`);
console.log('Claude execution validation passed: automatic qualified stock buys, automatic qualified crypto, automatic exits, Robinhood MCP only.');
