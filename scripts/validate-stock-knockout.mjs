import fs from 'node:fs/promises';
const signal=JSON.parse(await fs.readFile('docs/signal.json','utf8'));
const tournament=JSON.parse(await fs.readFile('docs/data/stock-tournament.json','utf8'));
const fail=[];
if(Number(signal.schemaVersion)<29)fail.push('signal schema <29');
if(signal.stockTournament?.enabled!==true)fail.push('signal tournament disabled');
if(Number(signal.stockTournament?.targetTournamentSize)!==20000)fail.push('target tournament size');
if(signal.stockTournament?.scanAllAvailableUpToTarget!==true)fail.push('scan-all-available rule');
if(signal.stockTournament?.alwaysProduceResearchChampion!==true)fail.push('research champion requirement');
if(signal.stockTournament?.alwaysBuySomething!==false)fail.push('forced-buy lock');
if(signal.stockTournament?.buyWhenAtLeastOneFullyQualifiedLiveCandidateExists!==true)fail.push('buy-good-candidate rule');
if(signal.stockTournament?.noEligibleCandidateAction!=='HOLD_CASH_AND_KEEP_SCANNING')fail.push('no-eligible action');
if(tournament.source!=='TESTSTOCK_UP_TO_20000_STOCK_KNOCKOUT')fail.push('tournament source');
if(Number(tournament.policy?.targetTournamentSize)!==20000)fail.push('tournament policy size');
if(tournament.policy?.scanAllAvailableUpToTarget!==true)fail.push('tournament scan-all rule');
if(!Array.isArray(tournament.rounds)||tournament.rounds.length<6)fail.push('knockout rounds');
const expected=['UNIVERSE','UP_TO_20000','TOP_2000','TOP_800','TOP_100','LIVE_FINAL'];
for(const r of expected)if(!tournament.rounds?.some(x=>x.round===r))fail.push(`missing round ${r}`);
if(!Array.isArray(tournament.researchFinalists)||tournament.researchFinalists.length<1)fail.push('research finalists');
if(tournament.policy?.alwaysBuySomething!==false)fail.push('tournament forced-buy lock');
if(tournament.policy?.buyWhenAtLeastOneFullyQualifiedLiveCandidateExists!==true)fail.push('tournament buy-good-candidate rule');
if(signal.generatorIntegrity?.traceableFeatures?.stockKnockoutTournament!==true)fail.push('integrity feature');
if(fail.length)throw new Error(`stock knockout validation failed: ${[...new Set(fail)].join(', ')}`);
console.log(`stock knockout validation passed: target up to 20000, actual universe ${tournament.policy?.actualAvailableUniverse||'unknown'}, ${tournament.researchFinalists.length} research finalists; live champion ${tournament.liveBuyChampion?.ticker||'none'}`);
