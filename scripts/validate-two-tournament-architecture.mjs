import fs from 'node:fs/promises';
const s=JSON.parse(await fs.readFile('docs/signal.json','utf8'));
const fail=[];
const a=s.executionArchitecture;
if(s.schemaVersion<43)fail.push('schema <43');
if(a?.mode!=='TWO_TOURNAMENTS_ONLY')fail.push('architecture mode');
if(a?.researchAuthority!=='TESTSTOCK')fail.push('research authority');
if(a?.tournaments?.stock?.enabled!==true)fail.push('stock tournament');
if(a?.tournaments?.stock?.operatingMode!=='CONTINUOUS_SCAN_SELECTIVE_INTRADAY_MULTI_POSITION')fail.push('stock intraday mode');
if(a?.tournaments?.stock?.validationScope!=='REGIME_SPECIFIC')fail.push('stock regime validation');
if(a?.tournaments?.crypto?.enabled!==true)fail.push('crypto tournament');
if(a?.crossAssetSelection!==false)fail.push('cross-asset selection');
if(JSON.stringify(a?.liveDecisionPaths)!==JSON.stringify(['STOCK_TOURNAMENT','CRYPTO_TOURNAMENT']))fail.push('live decision paths');
if(!Array.isArray(a?.disabledAssetClasses)||!a.disabledAssetClasses.includes('FUTURES')||a.disabledAssetClasses.includes('OPTION'))fail.push('asset class disable state');
if(s.stockPlan?.eliteOption&&s.stockPlan.eliteOption.liveEvidenceGate?.required!==true)fail.push('option live-evidence gate missing');
for(const t of s.capitalLadder?.tiers||[]){
  const optionsShouldBeAllowed=!['RECOVERY','DEFENSE'].includes(t.label);
  if(t.newOptionsAllowed!==optionsShouldBeAllowed)fail.push('capital tier option risk');
  if(optionsShouldBeAllowed&&!(Number(t.maxOptionRiskPct)>0))fail.push('capital tier option risk');
  if(!optionsShouldBeAllowed&&Number(t.maxOptionRiskPct||0)!==0)fail.push('capital tier option risk');
}
if(Number(s.tradeFrequencyGuard?.maxNewOptionsPerDay||0)!==1)fail.push('option frequency');
if(Number(s.executionQuality?.maxOptionSpreadPct)!==10)fail.push('option execution quality inactive');
if(!s.probabilityFirstPolicy?.options||s.probabilityFirstPolicy.options.requireLiveRealFillEvidence!==true)fail.push('probability option evidence gate missing');
if(s.crossAssetOpportunityRanking!=null)fail.push('cross-asset ranking still present');
if(s.systemHealth?.crossAssetRanking!=null)fail.push('cross-asset health dependency still present');
if(!Object.prototype.hasOwnProperty.call(s.assetClassRouting||{},'OPTION'))fail.push('option asset routing missing');
const appliesTo=s.claudeExecutionPolicy?.buys?.appliesTo||[];
if(!appliesTo.includes('STOCK_A')||!appliesTo.includes('STOCK_B')||!appliesTo.includes('CRYPTO'))fail.push('Claude buy scope');
if(s.autopilot?.requiresPerOrderApproval!==false||s.autopilot?.automaticQualifiedBuys!==true)fail.push('automatic stock policy');
if(s.autopilot?.automaticQualifiedStockBuys!==true||s.autopilot?.automaticQualifiedCryptoBuys!==true)fail.push('automatic asset buys');
if(s.claudeExecutionPolicy?.buys?.explicitApprovalRequired!==false)fail.push('Claude approval still required');
if(s.claudeExecutionPolicy?.buys?.automaticWhenFullyQualifiedAndBrokerPermits!==true)fail.push('Claude automatic buy disabled');
if(s.autopilot?.automaticRiskReducingExits!==true)fail.push('automatic exits disabled');
if(a?.tournaments?.stock?.execution?.includes('automatically submits qualified stock orders')!==true)fail.push('stock Claude MCP execution');
if(a?.tournaments?.crypto?.execution?.includes('authenticated Robinhood Trading MCP')!==true)fail.push('crypto Claude MCP execution');
if(s.cryptoTournament?.brokerExecution?.lane!=='CLAUDE_ROBINHOOD_TRADING_MCP')fail.push('crypto broker lane');
if(s.cryptoTournament?.brokerExecution?.executableByDirectRobinhoodCryptoApi!==false)fail.push('direct crypto API still enabled');
if(s.cryptoTournament?.brokerExecution?.directGitHubOrderSubmissionAllowed!==false)fail.push('GitHub order submission enabled');
if(s.cryptoTournament?.brokerExecution?.executableByCurrentClaudeRobinhoodConnection!==true)fail.push('Claude crypto execution unavailable');
if(s.intradayStockPolicy?.enabled!==true)fail.push('intraday stock policy');
if(s.intradayStockPolicy?.mode!=='CONTINUOUS_SCAN_SELECTIVE_MULTI_POSITION_TRADING')fail.push('intraday policy mode');
if(s.intradayStockPolicy?.systemWideEntryPauseFromGlobalValidationStatus!==false)fail.push('global validation pause still enabled');
if(s.intradayStockPolicy?.regimeSpecificValidationRequired!==true)fail.push('regime-specific validation required');
if(s.intradayStockPolicy?.forcedTradeQuota!==false)fail.push('forced trade quota');
if(s.intradayStockPolicy?.multipleConcurrentPositionsAllowed!==true)fail.push('multi-position policy');
if(s.intradayStockPolicy?.continueScanningWhilePositionsOpen!==true)fail.push('continue scanning policy');
if(s.intradayStockPolicy?.perOrderApprovalRequired!==false)fail.push('stock approval still required');
const hard=(s.hardRules||[]).join(' ').toLowerCase();
if(!hard.includes('options are exceptional'))fail.push('missing option hard rule');
if(!hard.includes('regime-specific validation'))fail.push('regime-specific hard rule');
if(!hard.includes('automatic stock execution'))fail.push('automatic stock hard rule');
if(!hard.includes('automatic crypto execution'))fail.push('automatic crypto hard rule');
if(s.generatorIntegrity?.traceableFeatures?.twoTournamentArchitecture!==true)fail.push('integrity marker');
if(s.generatorIntegrity?.traceableFeatures?.regimeSpecificStockValidation!==true)fail.push('regime validation integrity marker');
if(s.generatorIntegrity?.traceableFeatures?.selectiveIntradayStockMode!==true)fail.push('intraday integrity marker');
if(s.generatorIntegrity?.traceableFeatures?.automaticQualifiedStockBuys!==true)fail.push('automatic stock integrity marker');
if(s.generatorIntegrity?.traceableFeatures?.automaticQualifiedCryptoBuys!==true)fail.push('automatic crypto integrity marker');
if(s.generatorIntegrity?.traceableFeatures?.claudeRobinhoodTradingMcpExecution!==true)fail.push('Claude MCP integrity marker');
if(s.generatorIntegrity?.traceableFeatures?.perOrderOptionApproval!==true)fail.push('option approval integrity marker');
if(fail.length)throw new Error(`two-tournament validation failed: ${[...new Set(fail)].join(', ')}`);
console.log('two-tournament architecture validation passed: qualified stocks+crypto are automatic through Claude Robinhood Trading MCP; options remain separately approval-gated.');
